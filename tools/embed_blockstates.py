#!/usr/bin/env python3
"""Embed the block-state palette as Rust source inside the engine crate.

A bundle may hold Rust and TOML, and other files only under the mod's `data/`.
A crate cannot reach that: the mixins stage copies the crate to
`native-crates/<mod-id>/<crate-id>/`, leaving the mod's own folders behind, and
`horizon-mods` refuses a non-source file inside the crate. So the gzipped
palette becomes a byte array the crate includes.

Regenerate after changing `mixins/bedrock_bridge/data/blockstates-*.txt.gz`:

    python3 tools/embed_blockstates.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'mixins/bedrock_bridge/data/blockstates-1.26.60.txt.gz'
OUT = ROOT / 'mixins/bedrock_bridge/engine/src/blockstates_1_26_60.rs'
PER_ROW = 16

data = SRC.read_bytes()
rows = [data[i:i + PER_ROW] for i in range(0, len(data), PER_ROW)]
body = ''.join('    ' + ', '.join(f'0x{b:02x}' for b in row) + ',\n' for row in rows)
OUT.write_text(
    '// Generated by tools/embed_blockstates.py from\n'
    f'// data/{SRC.name}: {len(data)} gzipped bytes. Do not edit.\n'
    'pub const BUNDLED: &[u8] = &[\n'
    + body
    + '];\n'
)
print(f'{OUT.relative_to(ROOT)}: {len(data)} bytes')
