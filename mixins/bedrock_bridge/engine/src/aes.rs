const RCON: [u8; 15] = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36, 0x6c, 0xd8, 0xab, 0x4d,
];

/// An AES-256 key schedule.
pub struct Aes256 {
    round_keys: [u8; BLOCK * (NR + 1)],
}

#[inline]
fn xtime(x: u8) -> u8 {
    (x << 1) ^ if x & 0x80 != 0 { 0x1b } else { 0 }
}

#[inline]
fn gmul(mut a: u8, mut b: u8) -> u8 {
    let mut p = 0u8;
    for _ in 0..8 {
        if b & 1 != 0 {
            p ^= a;
        }
        let hi = a & 0x80;
        a <<= 1;
        if hi != 0 {
            a ^= 0x1b;
        }
        b >>= 1;
    }
    p
}

impl Aes256 {
    pub fn new(key: &[u8; 32]) -> Self {
        let mut w = [0u8; BLOCK * (NR + 1)];
        w[..32].copy_from_slice(key);
        for i in NK..(NB * (NR + 1)) {
            let mut temp = [
                w[(i - 1) * 4],
                w[(i - 1) * 4 + 1],
                w[(i - 1) * 4 + 2],
                w[(i - 1) * 4 + 3],
            ];
            if i % NK == 0 {
                temp = [temp[1], temp[2], temp[3], temp[0]];
                for t in temp.iter_mut() {
                    *t = SBOX[*t as usize];
                }
                temp[0] ^= RCON[i / NK];
            } else if i % NK == 4 {
                for t in temp.iter_mut() {
                    *t = SBOX[*t as usize];
                }
            }
            for j in 0..4 {
                w[i * 4 + j] = w[(i - NK) * 4 + j] ^ temp[j];
            }
        }
        Aes256 { round_keys: w }
    }

    fn add_round_key(&self, state: &mut [u8; BLOCK], round: usize) {
        for i in 0..BLOCK {
            state[i] ^= self.round_keys[round * BLOCK + i];
        }
    }

    fn sub_bytes(state: &mut [u8; BLOCK], boxed: &[u8; 256]) {
        for b in state.iter_mut() {
            *b = boxed[*b as usize];
        }
    }

    // State is column-major: index = row + 4*col.
    fn shift_rows(state: &mut [u8; BLOCK]) {
        let mut t = [0u8; BLOCK];
        for c in 0..4 {
            for r in 0..4 {
                t[r + 4 * c] = state[r + 4 * ((c + r) % 4)];
            }
        }
        *state = t;
    }
    fn inv_shift_rows(state: &mut [u8; BLOCK]) {
        let mut t = [0u8; BLOCK];
        for c in 0..4 {
            for r in 0..4 {
                t[r + 4 * c] = state[r + 4 * ((c + 4 - r) % 4)];
            }
        }
        *state = t;
    }

    fn mix_columns(state: &mut [u8; BLOCK]) {
        for c in 0..4 {
            let i = 4 * c;
            let (a0, a1, a2, a3) = (state[i], state[i + 1], state[i + 2], state[i + 3]);
            state[i] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
            state[i + 1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
            state[i + 2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
            state[i + 3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
        }
    }
    fn inv_mix_columns(state: &mut [u8; BLOCK]) {
        for c in 0..4 {
            let i = 4 * c;
            let (a0, a1, a2, a3) = (state[i], state[i + 1], state[i + 2], state[i + 3]);
            state[i] = gmul(a0, 14) ^ gmul(a1, 11) ^ gmul(a2, 13) ^ gmul(a3, 9);
            state[i + 1] = gmul(a0, 9) ^ gmul(a1, 14) ^ gmul(a2, 11) ^ gmul(a3, 13);
            state[i + 2] = gmul(a0, 13) ^ gmul(a1, 9) ^ gmul(a2, 14) ^ gmul(a3, 11);
            state[i + 3] = gmul(a0, 11) ^ gmul(a1, 13) ^ gmul(a2, 9) ^ gmul(a3, 14);
        }
    }

    pub fn encrypt_block(&self, block: &mut [u8; BLOCK]) {
        self.add_round_key(block, 0);
        for round in 1..NR {
            Self::sub_bytes(block, &SBOX);
            Self::shift_rows(block);
            Self::mix_columns(block);
            self.add_round_key(block, round);
        }
        Self::sub_bytes(block, &SBOX);
        Self::shift_rows(block);
        self.add_round_key(block, NR);
    }

    pub fn decrypt_block(&self, block: &mut [u8; BLOCK]) {
        self.add_round_key(block, NR);
        for round in (1..NR).rev() {
            Self::inv_shift_rows(block);
            Self::sub_bytes(block, &INV_SBOX);
            self.add_round_key(block, round);
            Self::inv_mix_columns(block);
        }
        Self::inv_shift_rows(block);
        Self::sub_bytes(block, &INV_SBOX);
        self.add_round_key(block, 0);
    }

    /// ECB-encrypt every 16-byte block (the buffer must be a multiple of 16).
    pub fn encrypt_ecb(&self, data: &mut [u8]) {
        for chunk in data.chunks_exact_mut(BLOCK) {
            let mut block = [0u8; BLOCK];
            block.copy_from_slice(chunk);
            self.encrypt_block(&mut block);
            chunk.copy_from_slice(&block);
        }
    }

    /// ECB-decrypt every 16-byte block.
    pub fn decrypt_ecb(&self, data: &mut [u8]) {
        for chunk in data.chunks_exact_mut(BLOCK) {
            let mut block = [0u8; BLOCK];
            block.copy_from_slice(chunk);
            self.decrypt_block(&mut block);
            chunk.copy_from_slice(&block);
        }
    }
}

/// NetherNet discovery padding: pad to a whole block with `padding_len` repeated,
/// always adding 1..=16 bytes even when already aligned.
pub fn pad(buf: &mut Vec<u8>) {
    let padding_len = BLOCK - (buf.len() % BLOCK);
    buf.resize(buf.len() + padding_len, padding_len as u8);
}

/// Strip the discovery padding, verifying every pad byte.
pub fn unpad(buf: &mut Vec<u8>) -> Option<()> {
    let len = buf.len();
    if len == 0 || len % BLOCK != 0 {
        return None;
    }
    let padding_len = *buf.last()? as usize;
    if padding_len == 0 || padding_len > BLOCK || padding_len > len {
        return None;
    }
    let start = len - padding_len;
    if buf[start..].iter().all(|&b| b as usize == padding_len) {
        buf.truncate(start);
        Some(())
    } else {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // FIPS-197 C.3 (AES-256) test vector.
    #[test]
    fn fips_197_aes256_vector() {
        let key: [u8; 32] = [
            0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d,
            0x0e, 0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b,
            0x1c, 0x1d, 0x1e, 0x1f,
        ];
        let mut block = [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
            0xee, 0xff,
        ];
        let cipher = Aes256::new(&key);
        cipher.encrypt_block(&mut block);
        assert_eq!(
            block,
            [
                0x8e, 0xa2, 0xb7, 0xca, 0x51, 0x67, 0x45, 0xbf, 0xea, 0xfc, 0x49, 0x90, 0x4b, 0x49,
                0x60, 0x89
            ]
        );
        cipher.decrypt_block(&mut block);
        assert_eq!(
            block,
            [
                0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
                0xee, 0xff
            ]
        );
    }

    #[test]
    fn padding_round_trips_and_validates() {
        for n in 0..40 {
            let mut buf = vec![7u8; n];
            pad(&mut buf);
            assert_eq!(buf.len() % BLOCK, 0);
            assert!(buf.len() > n);
            unpad(&mut buf).unwrap();
            assert_eq!(buf, vec![7u8; n]);
        }
        let mut bad = vec![0u8; 32];
        bad[31] = 0xff;
        assert!(unpad(&mut bad).is_none());
    }
}
